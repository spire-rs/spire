#![forbid(unsafe_code)]
#![cfg_attr(docsrs, feature(doc_cfg))]
// The README is the crate's documentation. Its examples need several
// features, so they are doctested only with `full` and `testing`, through
// `ReadmeDoctests`.
#![cfg_attr(not(doctest), doc = include_str!("../README.md"))]

pub mod extract;
pub mod handler;
mod routing;

#[doc(hidden)]
pub mod prelude;

use spire_core::backend::Backend;
#[cfg(any(test, feature = "testing"))]
#[cfg_attr(docsrs, doc(cfg(feature = "testing")))]
pub use spire_core::testing;
pub use spire_core::{Context, Error, ErrorKind, Result, worker};

pub use crate::routing::Router;

/// Backends and the clients they hand out, plus the enabled HTTP and browser
/// backends.
pub mod backend {
    pub use spire_core::backend::*;
    #[cfg(feature = "reqwest")]
    #[cfg_attr(docsrs, doc(cfg(feature = "reqwest")))]
    pub use spire_reqwest::{HttpClient, reqwest};
    #[cfg(feature = "thirtyfour")]
    #[cfg_attr(docsrs, doc(cfg(feature = "thirtyfour")))]
    pub use spire_thirtyfour::{BrowserBackend, BrowserBuilder, BrowserSession, thirtyfour};
}

/// The crawler's settings and statistics; the [`Crawler`] itself is at the
/// crate root.
pub mod crawler {
    #[cfg(feature = "robots")]
    #[cfg_attr(docsrs, doc(cfg(feature = "robots")))]
    pub use spire_core::crawler::Robots;
    pub use spire_core::crawler::{HostConcurrency, Stats};

    #[cfg(doc)]
    use crate::Crawler;
}

/// Datasets: where handlers store what they scrape.
pub mod dataset {
    // Listed by name, so the documentation shows the features of this crate.
    #[cfg(feature = "csv")]
    #[cfg_attr(docsrs, doc(cfg(feature = "csv")))]
    pub use spire_core::dataset::CsvDataset;
    #[cfg(feature = "json")]
    #[cfg_attr(docsrs, doc(cfg(feature = "json")))]
    pub use spire_core::dataset::JsonlDataset;
    pub use spire_core::dataset::{Data, Dataset, InMemDataset, READ_BATCH};
}

/// The frontier: requests waiting to be crawled.
pub mod frontier {
    pub use spire_core::frontier::*;
}

/// A crawl stored in redb: a crash-safe frontier, seen set and datasets in
/// one file, see [`RedbStore`](crate::redb::RedbStore).
#[cfg(feature = "redb")]
#[cfg_attr(docsrs, doc(cfg(feature = "redb")))]
pub mod redb {
    pub use spire_redb::{
        RedbDataset, RedbFrontier, RedbSeen, RedbStore, RedbStoreBuilder, RedbValidators, redb,
    };
}

/// Requests, responses and their crawl metadata.
pub mod request {
    pub use spire_core::http;
    pub use spire_core::request::*;
    #[cfg(feature = "macros")]
    #[cfg_attr(docsrs, doc(cfg(feature = "macros")))]
    pub use spire_macros::{Revisit, Tags};
}

/// Crawls requests with a [`Backend`], handling them with a [`Router`] by
